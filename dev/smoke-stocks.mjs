// node dev/smoke-stocks.mjs <out> [base] : Robinhood Chain stocks, pool quotes, pair trades, alerts, liquidation odds
import { writeFileSync } from 'node:fs';
import { launch, sleep } from './cdp.mjs';
const [out, base = 'http://localhost:8792'] = process.argv.slice(2);
const tab = await launch({ width: 1600, height: 1000 });
await tab.send('Page.addScriptToEvaluateOnNewDocument', { source: `window.__errs=[];addEventListener('error',e=>__errs.push(e.message+' @'+e.lineno));addEventListener('unhandledrejection',e=>__errs.push(String(e.reason)));if(!sessionStorage.k){localStorage.clear();sessionStorage.k=1}` });
await tab.goto(base + '/trade/?m=NVDA', 8000);
const ev = js => tab.eval(js);
const run = async c => { try { const r = await ev(`avenRun(${JSON.stringify(c)}).op`); console.log('ok  ', c); } catch (e) { console.log('FAIL', c, '→', e.message.split('\n')[0]); } await sleep(700); };
console.log('NVDA bar', await ev(`[...document.querySelectorAll('.t-bar .kv')].map(k=>k.innerText.replace(/\\n/g,' ')).join(' | ')`));
console.log('pool panel', await ev(`document.getElementById('book').innerText.replace(/\\n/g,' · ').slice(0,300)`));
console.log('ticket', await ev(`document.getElementById('summary').innerText.replace(/\\n/g,' · ')`));
await run('long nvda 5x 1000');
await run('long coin 5x 9000');
await run('pair long msft short qqq 800 3x');
await run('alert btc above 999999');
await run('alert nvda below 1');
await run('alert btc 1');
await sleep(4000);
const st = JSON.parse(await ev(`localStorage.getItem('aven.v2')`));
console.log('positions', JSON.stringify(Object.entries(st.pos).map(([k, p]) => [k, p.side, +p.entry.toFixed(3), +p.liq.toFixed(3), p.pair || null])));
console.log('fills', JSON.stringify(st.fills.slice(0, 4).map(f => [f.sym, f.side, +f.price.toFixed(3)])), 'alerts', st.alerts.length, 'pairs', st.pairs.length);
console.log('marks', await ev(`(async()=>{const f=await import('/assets/feed.js');return ['NVDA','MSFT','QQQ','BTC'].map(s=>s+' '+f.marks[s]).join(' · ')})()`));
await sleep(5000);
console.log('odds col', await ev(`[...document.querySelectorAll('#pos tr')].slice(1).map(r=>r.children[0].innerText.split(' ')[0]+' '+r.children[5]?.innerText).join(' | ')`));
writeFileSync(out + '/stocks.png', await tab.shot());
await ev(`document.querySelector('#tabs [data-t=ord]').click()`); await sleep(500);
writeFileSync(out + '/alerts.png', await tab.shot());
await run('close pair');
console.log('after close pair', JSON.stringify(Object.keys(JSON.parse(await ev(`localStorage.getItem('aven.v2')`)).pos)));
console.log('errors', await ev('JSON.stringify(__errs)'));
await tab.close();
